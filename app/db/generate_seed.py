#!/usr/bin/env python3
"""Write db/init/02-seed.sql: Brightlane's sites and tariffs, and the SQL that generates the
session charges of 1 to 21 October 2026 inside PostgreSQL (deterministic: setseed).

The sites and tariffs come from the same generator logic as the Spark course
(`common/brightlane.py`, `build_network`, seed 2026), so names, charger counts and prices match.

    python3 app/db/generate_seed.py
"""
import random
from datetime import date, timedelta
from pathlib import Path

SEED = 2026
REGIONS = {"N": 14, "C": 12, "V": 10}
CHARGERS_TOTAL = 240
TOWNS = {
    "N": ["Hollin Moor", "Ashby Cross", "Kelderby", "Northope", "Fallowfield", "Ravensholt",
          "Cragmere", "Dunmoor", "Hartlow", "Elsby", "Thornwick", "Garthby", "Wolden", "Brackenridge"],
    "C": ["Saltmarsh", "Port Elver", "Gullhaven", "Shingle Bay", "Westerby", "Tidewell",
          "Marrow Point", "Sandcombe", "Larkhaven", "Easterness", "Coveley", "Brinemouth"],
    "V": ["Millbeck", "Orchard Vale", "Lindhurst", "Ferncombe", "Willowford", "Ashvale",
          "Riverslea", "Hayden Bottom", "Meadowcroft", "Greywell"],
}
PLACES = ["Market Square", "Retail Park", "Station Car Park", "Leisure Centre", "Park & Ride",
          "Town Hall", "Harbour Road", "Business Park"]
MODELS = {"Kestrel DC50": (50, "CCS2", 0.70), "Kestrel DC150": (150, "CCS2", 0.20), "Wren AC22": (22, "Type2", 0.10)}
LEGACY_SITES = {"site-V01", "site-V02", "site-V03"}


def build_network(rng):
    """Sites and tariffs, drawn in exactly the order the Spark course's generator draws them."""
    sites, tariffs = [], []
    counts = {f"site-{r}{i:02d}": rng.randint(4, 10) for r, n in REGIONS.items() for i in range(1, n + 1)}
    ids = sorted(counts)
    while sum(counts.values()) != CHARGERS_TOTAL:
        sid = rng.choice(ids)
        step = 1 if sum(counts.values()) < CHARGERS_TOTAL else -1
        if 4 <= counts[sid] + step <= 10:
            counts[sid] += step
    for region, n in REGIONS.items():
        towns = TOWNS[region][:]
        rng.shuffle(towns)
        for i in range(1, n + 1):
            sid = f"site-{region}{i:02d}"
            opened = date(2021, 3, 1) + timedelta(days=rng.randint(0, 1700))
            sites.append({"site_id": sid, "site_name": f"{towns[i - 1]} {rng.choice(PLACES)}",
                          "region": region, "town": towns[i - 1], "chargers": counts[sid],
                          "opened_on": opened.isoformat()})
            for c in range(1, counts[sid] + 1):  # chargers: drawn to keep the random sequence identical
                rng.choices(list(MODELS), weights=[m[2] for m in MODELS.values()])
                if sid in LEGACY_SITES:
                    rng.choice([6, 7])
                else:
                    rng.choice([1, 1, 3])
                rng.randint(0, 1900)
    for s in sites:
        sid = s["site_id"]
        idle = rng.choice([0.10, 0.10, 0.15, 0.0])
        price = round(rng.uniform(0.39, 0.55), 2)
        history = [(date(2025, 11, 1), price)]
        if sid == "site-N03":
            history = [(date(2026, 1, 1), 0.45), (date(2026, 10, 1), 0.49)]
        elif rng.random() < 0.3:
            history.append((date(2026, rng.choice([4, 7, 10]), 1), round(price + rng.choice([0.02, 0.03, 0.04]), 2)))
        for n, (valid_from, p) in enumerate(history, start=1):
            tariffs.append({"tariff_id": f"tar-{sid}-{n}", "site_id": sid, "price_per_kwh": f"{p:.2f}",
                            "idle_fee_per_min": f"{idle:.2f}", "valid_from": valid_from.isoformat()})
    return sites, tariffs


def sql_text(value):
    return "'" + str(value).replace("'", "''") + "'"


def main():
    sites, tariffs = build_network(random.Random(SEED))
    lines = ["-- Generated by db/generate_seed.py. Don't edit; run the script again.", "",
             "INSERT INTO sites (site_id, site_name, region, town, chargers, opened_on) VALUES"]
    lines.append(",\n".join(f"  ({sql_text(s['site_id'])}, {sql_text(s['site_name'])}, {sql_text(s['region'])}, "
                            f"{sql_text(s['town'])}, {s['chargers']}, DATE {sql_text(s['opened_on'])})" for s in sites) + ";")
    lines += ["", "INSERT INTO tariffs (tariff_id, site_id, price_per_kwh, idle_fee_per_min, valid_from) VALUES"]
    lines.append(",\n".join(f"  ({sql_text(t['tariff_id'])}, {sql_text(t['site_id'])}, {t['price_per_kwh']}, "
                            f"{t['idle_fee_per_min']}, DATE {sql_text(t['valid_from'])})" for t in tariffs) + ";")
    lines.append(SESSIONS)
    out = Path(__file__).parent / "init" / "02-seed.sql"
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(sites)} sites, {len(tariffs)} tariffs")


SESSIONS = """
-- Session charges for 1 to 21 October 2026: about 16 sessions per charger and day, fewer at the
-- weekend, 5 to 55 kWh each (30 on average), an idle fee for about one session in four.
-- setseed makes random() repeat the same sequence, so every lab gets the same rows.
SELECT setseed(0.2026);

CREATE TEMPORARY TABLE planned AS
SELECT s.site_id,
       s.chargers,
       d::date AS day,
       n,
       random() AS r_charger,
       random() AS r_start,
       random() AS r_minutes,
       random() AS r_energy,
       random() AS r_idle,
       random() AS r_idle_minutes
  FROM generate_series(DATE '2026-10-01', DATE '2026-10-21', INTERVAL '1 day') AS d
 CROSS JOIN sites AS s
 CROSS JOIN LATERAL generate_series(
           1,
           round(s.chargers * CASE WHEN extract(isodow FROM d) >= 6 THEN 11 ELSE 16 END)::int) AS n
 ORDER BY d, s.site_id, n;

INSERT INTO session_charges
       (session_id, site_id, charger_id, started_at, ended_at, energy_kwh, idle_minutes, tariff_id, amount_eur)
SELECT 'ses-' || to_hex(8323072 + row_number() OVER (ORDER BY p.day, p.site_id, p.n)),
       p.site_id,
       'BL-' || substr(p.site_id, 6) || '-' || lpad((1 + floor(p.r_charger * p.chargers))::text, 2, '0'),
       p.day + make_interval(secs => 21600 + floor(p.r_start * 57600)),
       p.day + make_interval(secs => 21600 + floor(p.r_start * 57600) + 600 + floor(p.r_minutes * 4200)),
       round((5 + p.r_energy * 50)::numeric, 3),
       CASE WHEN p.r_idle < 0.25 THEN 1 + floor(p.r_idle_minutes * 20)::int ELSE 0 END,
       t.tariff_id,
       round(round((5 + p.r_energy * 50)::numeric, 3) * t.price_per_kwh, 2)
         + CASE WHEN p.r_idle < 0.25 THEN (1 + floor(p.r_idle_minutes * 20)) * t.idle_fee_per_min ELSE 0 END
  FROM planned AS p
 CROSS JOIN LATERAL (
       SELECT tariff_id, price_per_kwh, idle_fee_per_min
         FROM tariffs
        WHERE site_id = p.site_id AND valid_from <= p.day
        ORDER BY valid_from DESC
        LIMIT 1) AS t;

DROP TABLE planned;
ANALYZE;
"""

if __name__ == "__main__":
    main()
