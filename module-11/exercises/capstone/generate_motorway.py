#!/usr/bin/env python3
"""Write motorway.sql: the 60 motorway service areas and their tariffs, for the capstone.

The sites come from the same generator logic as the Spark course (`common/motorway.py`, `reference`,
seed 2026), so names and charger counts match: site-M01 is Kestrel Gate Services, 360 chargers.
Every motorway site opens on 2 November 2026 at 0.50 EUR/kWh (the finance rulebook, lesson 4.4).

    python3 module-11/exercises/capstone/generate_motorway.py
"""
import random
from pathlib import Path

SEED = 2026
SITES = 60
CHARGERS = 6000
KESTREL_CHARGERS = 360
TOWNS = ["Kestrel Gate", "Harrow Fell", "Ostley Cross", "Brandmoor", "Wexley", "Calder Rise",
         "Fenwick", "Marston Heath", "Linton Edge", "Aldcote", "Pennbridge", "Sorrel Downs"]
OPENS = "2026-11-02"
PRICE, IDLE_FEE = "0.50", "0.10"


def reference(rng):
    """The Spark course's draws, in the same order (the charger models are drawn and discarded)."""
    counts = {"site-M01": KESTREL_CHARGERS}
    others = [f"site-M{i:02d}" for i in range(2, SITES + 1)]
    left = CHARGERS - KESTREL_CHARGERS
    for sid in others:
        counts[sid] = rng.randint(40, 120)
    while sum(counts[s] for s in others) != left:
        sid = rng.choice(others)
        step = 1 if sum(counts[s] for s in others) < left else -1
        if 40 <= counts[sid] + step <= 120:
            counts[sid] += step
    sites = []
    for sid in sorted(counts):
        name = TOWNS[0] if sid == "site-M01" else f"{rng.choice(TOWNS[1:])} {rng.choice(['North', 'South', 'East', 'West'])}"
        sites.append((sid, f"{name} Services", name, counts[sid]))
        for _ in range(counts[sid]):
            rng.choices(["Kestrel DC150", "Kestrel DC50"], [7, 3])
    return sites


def main():
    sites = reference(random.Random(SEED))
    quote = lambda s: "'" + s.replace("'", "''") + "'"
    lines = [
        "-- The motorway service areas (capstone): 60 sites, region M, open from 2 November 2026.",
        "-- Generated by generate_motorway.py. Safe to run more than once: existing rows are kept.",
        "INSERT INTO sites (site_id, site_name, region, town, chargers, opened_on) VALUES",
        ",\n".join(f"  ({quote(sid)}, {quote(name)}, 'M', {quote(town)}, {n}, DATE '{OPENS}')" for sid, name, town, n in sites),
        "ON CONFLICT (site_id) DO NOTHING;",
        "",
        "INSERT INTO tariffs (tariff_id, site_id, price_per_kwh, idle_fee_per_min, valid_from) VALUES",
        ",\n".join(f"  ('tar-{sid}-1', {quote(sid)}, {PRICE}, {IDLE_FEE}, DATE '{OPENS}')" for sid, *_ in sites),
        "ON CONFLICT (tariff_id) DO NOTHING;",
        "",
    ]
    out = Path(__file__).with_name("motorway.sql")
    out.write_text("\n".join(lines))
    print(f"{out}: {len(sites)} sites, {sum(n for *_, n in sites)} chargers")


if __name__ == "__main__":
    main()
